#!/usr/bin/env bash
# Build the PicoMEM firmware on a case-sensitive filesystem.
#
# src/USB_Host_Driver (capital D) and src/USB_Host_driver (lowercase d) are one
# directory on Windows/macOS but two on Linux, and CMake needs the merged
# result. Rather than renaming anything in the repository, this builds from a
# temporary copy of src/ with the two merged. The working tree is not modified.
#
# See BUILDING.md for the prerequisites.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$REPO/build}"
STAGE_DIR="${STAGE_DIR:-${TMPDIR:-/tmp}/picomem-src}"
NO_USB=0

while [ $# -gt 0 ]; do
    case "$1" in
        --no-usb) NO_USB=1 ;;
        -h|--help)
            echo "usage: $0 [--no-usb]"
            echo "  --no-usb   force DO_USBHOST 0 in the staged copy. Needed until"
            echo "             the TinyUSB revision is pinned, see BUILDING.md."
            exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

if [ -z "${PICO_SDK_PATH:-}" ]; then
    echo "PICO_SDK_PATH is not set. See BUILDING.md section 2." >&2
    exit 1
fi
if [ ! -f "$PICO_SDK_PATH/lib/lwip/src/core/init.c" ]; then
    echo "lwIP not found in the SDK. Run, in $PICO_SDK_PATH:" >&2
    echo "  git submodule update --init lib/lwip lib/cyw43-driver" >&2
    exit 1
fi
if ! command -v arm-none-eabi-gcc >/dev/null; then
    echo "arm-none-eabi-gcc not found. See BUILDING.md section 1." >&2
    exit 1
fi

echo "==> Staging sources in $STAGE_DIR"
rm -rf "$STAGE_DIR"
cp -r "$REPO/src" "$STAGE_DIR"

# Merge the case-variant USB directories (no-clobber: the capital D copy wins)
if [ -d "$STAGE_DIR/USB_Host_driver" ] && [ -d "$STAGE_DIR/USB_Host_Driver" ]; then
    echo "==> Merging USB_Host_driver into USB_Host_Driver"
    cp -rn "$STAGE_DIR/USB_Host_driver/." "$STAGE_DIR/USB_Host_Driver/"
fi

if [ "$NO_USB" = 0 ]; then
    # tusb_config.h sets CFG_TUH_MIDI 1. usbh.c uses AUDIO_SUBCLASS_CONTROL under
    # that guard and only gets the definition through tusb.h -> midi_host.h ->
    # class/audio/audio.h. midi_host.h (native MIDI host) first exists in
    # TinyUSB 0.19.0, so anything older fails to compile. Say so plainly rather
    # than letting it surface as an undeclared identifier.
    if [ ! -f "$STAGE_DIR/lib/tinyusb/src/class/midi/midi_host.h" ]; then
        echo "TinyUSB at src/lib/tinyusb is too old: no class/midi/midi_host.h." >&2
        echo "CFG_TUH_MIDI needs 0.19.0 or newer (0.21.0 recommended)." >&2
        echo "See BUILDING.md section 3." >&2
        exit 1
    fi

    # Documented at the top of USB_Host_Driver2/CMakeLists.txt:
    # "!! Remove link of tinyusb in xinput CMakefile !!". Without this the link
    # fails with "cannot find -ltinyusb", since the TinyUSB sources are already
    # compiled into the picomem target.
    if grep -q "INTERFACE tinyusb)" "$STAGE_DIR/lib/tusb_xinput/CMakeLists.txt" 2>/dev/null; then
        echo "==> Removing the tinyusb link from tusb_xinput (see USB_Host_Driver2/CMakeLists.txt)"
        sed -i 's|^target_link_libraries(xinput_host INTERFACE tinyusb)|# removed by tools/build-linux.sh, see USB_Host_Driver2/CMakeLists.txt|' \
            "$STAGE_DIR/lib/tusb_xinput/CMakeLists.txt"
    fi
fi

if [ "$NO_USB" = 1 ]; then
    echo "==> Forcing DO_USBHOST 0 in the staged copy"
    sed -i 's/^\( *\)set(DO_USBHOST 1)/\1set(DO_USBHOST 0)/' "$STAGE_DIR/CMakeLists.txt"

    # pm_libs compiles inputs/pm_inputs.c and inputs/players/player.c
    # unconditionally, and both include tusb.h through inputs/manager.h. With
    # the USB host off the TinyUSB include paths are not set, so they cannot
    # build. Their only consumers outside inputs/ are USB_Host_Driver2 (not
    # compiled here) and the two entry points stubbed below.
    echo "==> Stubbing the TinyUSB dependent input sources"
    sed -i -e '\|inputs/players/player.c|d' -e '\|inputs/pm_inputs.c|d' \
        "$STAGE_DIR/pm_libs/CMakeLists.txt"
    cat > "$STAGE_DIR/pm_libs/input_stubs.c" <<'STUB'
/* Generated by tools/build-linux.sh --no-usb, see the note there. */
void pm_input_init(void) {}
void pm_input_task(void) {}
STUB
    sed -i 's|\( *\)${CMAKE_CURRENT_LIST_DIR}/inputs/buttons/sp_buttons.c|&\n\1${CMAKE_CURRENT_LIST_DIR}/input_stubs.c|' \
        "$STAGE_DIR/pm_libs/CMakeLists.txt"
fi

echo "==> Configuring"
cmake -S "$STAGE_DIR" -B "$BUILD_DIR" -G Ninja ${CMAKE_EXTRA:-}

echo "==> Building"
cmake --build "$BUILD_DIR"

echo
echo "==> Done"
ls -lh "$BUILD_DIR"/picomem.uf2 "$BUILD_DIR"/picomem.elf 2>/dev/null || true
